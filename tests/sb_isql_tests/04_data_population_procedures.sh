CREATE PROCEDURE bulk_populate_with_transactions(table_name VARCHAR(50), batch_size INTEGER, total_records INTEGER)
AS
DECLARE VARIABLE batch_counter INTEGER;
DECLARE VARIABLE record_counter INTEGER;
DECLARE VARIABLE records_in_batch INTEGER;
BEGIN
    batch_counter = 1;
    record_counter = 1;
    
    -- Process in batches for better transaction management
    WHILE (record_counter <= total_records) DO
    BEGIN
        -- Start new transaction for each batch
        records_in_batch = 0;
        
        WHILE (records_in_batch < batch_size AND record_counter <= total_records) DO
        BEGIN
            -- Insert sample data (simplified for demo)
            IF (table_name = 'SAMPLE_DATA') THEN
            BEGIN
                INSERT INTO test_data.samples.sample_transactions (
                    transaction_code, transaction_amount, transaction_date, description
                ) VALUES (
                    'BULK' || LPAD(CAST(record_counter AS VARCHAR(8)), 8, '0'),
                    test_data.utilities.generate_random_decimal(1.00, 1000.00, 2),
                    test_data.utilities.generate_random_date('2024-01-01', '2025-01-31'),
                    'Bulk generated transaction #' || CAST(record_counter AS VARCHAR(10))
                );
            END
            
            records_in_batch = records_in_batch + 1;
            record_counter = record_counter + 1;
        END
        
        -- Commit batch
        batch_counter = batch_counter + 1;
    END
END;

