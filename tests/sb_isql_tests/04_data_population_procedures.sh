-- Procedure to populate orders and order items
CREATE PROCEDURE populate_orders_with_items(order_count INTEGER, max_items_per_order INTEGER)
AS
DECLARE VARIABLE order_counter INTEGER;
DECLARE VARIABLE item_counter INTEGER;
DECLARE VARIABLE items_in_order INTEGER;
DECLARE VARIABLE random_customer_id INTEGER;
DECLARE VARIABLE random_product_id INTEGER;
DECLARE VARIABLE random_quantity INTEGER;
DECLARE VARIABLE random_unit_price DECIMAL(10,2);
DECLARE VARIABLE random_order_date DATE;
DECLARE VARIABLE current_order_id INTEGER;
DECLARE VARIABLE order_subtotal DECIMAL(12,2);
DECLARE VARIABLE order_tax DECIMAL(10,2);
DECLARE VARIABLE order_total DECIMAL(12,2);
BEGIN
    order_counter = 1;
    
    WHILE (order_counter <= order_count) DO
    BEGIN
        -- Select random customer (assume customers exist)
        random_customer_id = test_data.utilities.generate_random_int(1, 100);
        random_order_date = test_data.utilities.generate_random_date('2024-01-01', '2025-01-31');
        
        -- Insert order
        INSERT INTO orders (
            order_number, customer_id, order_date,
            order_status, payment_method, payment_status,
            currency, shipping_country
        ) VALUES (
            'ORD' || LPAD(CAST(order_counter AS VARCHAR(8)), 8, '0'),
            random_customer_id, random_order_date,
            CASE WHEN MOD(order_counter, 5) = 0 THEN 'COMPLETED'
                 WHEN MOD(order_counter, 5) = 1 THEN 'SHIPPED'
                 WHEN MOD(order_counter, 5) = 2 THEN 'PROCESSING'
                 WHEN MOD(order_counter, 5) = 3 THEN 'PENDING'
                 ELSE 'CANCELLED' END,
            CASE WHEN MOD(order_counter, 3) = 0 THEN 'CREDIT_CARD'
                 WHEN MOD(order_counter, 3) = 1 THEN 'DEBIT_CARD'
                 ELSE 'CASH' END,
            CASE WHEN MOD(order_counter, 8) <> 0 THEN 'PAID' ELSE 'PENDING' END,
            'USD', 'USA'
        );
        
        -- Get the order ID
        current_order_id = GEN_ID(GEN_ORDERS_ORDER_ID, 0);
        
        -- Generate random number of items for this order
        items_in_order = test_data.utilities.generate_random_int(1, max_items_per_order);
        item_counter = 1;
        order_subtotal = 0;
        
        WHILE (item_counter <= items_in_order) DO
        BEGIN
            random_product_id = test_data.utilities.generate_random_int(1, 50);
            random_quantity = test_data.utilities.generate_random_int(1, 5);
            random_unit_price = test_data.utilities.generate_random_decimal(25.00, 500.00, 2);
            
            INSERT INTO order_items (
                order_id, product_id, quantity, unit_price,
                discount_percent, discount_amount
            ) VALUES (
                current_order_id, random_product_id, random_quantity, random_unit_price,
                CASE WHEN MOD(item_counter, 4) = 0 THEN 10.00 ELSE 0.00 END,
                CASE WHEN MOD(item_counter, 4) = 0 THEN (random_quantity * random_unit_price * 0.10) ELSE 0.00 END
            );
            
            order_subtotal = order_subtotal + (random_quantity * random_unit_price);
            item_counter = item_counter + 1;
        END
        
        -- Update order totals
        order_tax = order_subtotal * 0.0825;
        order_total = order_subtotal + order_tax;
        
        UPDATE orders 
        SET subtotal = order_subtotal,
            tax_amount = order_tax,
            total_amount = order_total,
            shipping_amount = CASE WHEN order_total > 100 THEN 0 ELSE 9.99 END
        WHERE order_id = current_order_id;
        
        order_counter = order_counter + 1;
    END
END;

