-- Generate random email
CREATE FUNCTION generate_random_email(first_name VARCHAR(50), last_name VARCHAR(50))
RETURNS VARCHAR(255)
AS
BEGIN
    DECLARE domain_num INTEGER;
    DECLARE domain_name VARCHAR(50);
    
    domain_num = MOD(EXTRACT(SECOND FROM CURRENT_TIMESTAMP), 5);
    
    IF (domain_num = 0) THEN domain_name = 'email.com';
    ELSE IF (domain_num = 1) THEN domain_name = 'company.org';
    ELSE IF (domain_num = 2) THEN domain_name = 'business.net';
    ELSE IF (domain_num = 3) THEN domain_name = 'enterprise.com';
    ELSE domain_name = 'professional.org';
    
    RETURN LOWER(SUBSTRING(first_name FROM 1 FOR 1) || last_name || 
                CAST(MOD(EXTRACT(MILLISECOND FROM CURRENT_TIMESTAMP), 100) AS VARCHAR(3)) || 
                '@' || domain_name);
END;

