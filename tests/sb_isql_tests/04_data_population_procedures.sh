-- Random number generator function (using system features)
CREATE FUNCTION generate_random_int(min_val INTEGER, max_val INTEGER)
RETURNS INTEGER
AS
BEGIN
    -- Use current timestamp for pseudo-randomness
    RETURN min_val + MOD(EXTRACT(MILLISECOND FROM CURRENT_TIMESTAMP) * 
                        EXTRACT(SECOND FROM CURRENT_TIMESTAMP) * 
                        EXTRACT(MINUTE FROM CURRENT_TIMESTAMP), 
                        (max_val - min_val + 1));
END;

-- Random decimal generator
CREATE FUNCTION generate_random_decimal(min_val DECIMAL(10,2), max_val DECIMAL(10,2), precision_places INTEGER)
RETURNS DECIMAL(10,2)
AS
BEGIN
    DECLARE random_factor DECIMAL(10,6);
    DECLARE range_val DECIMAL(10,2);
    DECLARE result_val DECIMAL(10,2);
    
    -- Generate pseudo-random factor between 0 and 1
    random_factor = MOD(EXTRACT(MILLISECOND FROM CURRENT_TIMESTAMP) * 
                       EXTRACT(SECOND FROM CURRENT_TIMESTAMP), 1000000) / 1000000.0;
    
    range_val = max_val - min_val;
    result_val = min_val + (range_val * random_factor);
    
    -- Round to specified precision
    IF (precision_places = 2) THEN
        result_val = ROUND(result_val, 2);
    ELSE
        result_val = ROUND(result_val, precision_places);
    
    RETURN result_val;
END;

-- Random date generator
CREATE FUNCTION generate_random_date(start_date DATE, end_date DATE)
RETURNS DATE
AS
BEGIN
    DECLARE date_range INTEGER;
    DECLARE random_days INTEGER;
    
    date_range = end_date - start_date;
    random_days = MOD(EXTRACT(MILLISECOND FROM CURRENT_TIMESTAMP) * 
                     EXTRACT(MINUTE FROM CURRENT_TIMESTAMP), date_range);
    
    RETURN start_date + random_days;
END;

